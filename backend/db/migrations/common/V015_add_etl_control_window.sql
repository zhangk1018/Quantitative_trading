-- =====================================================================
-- V015: 港股/美股下载 断点续传游标 —— etl_control 增加 last_processed_window 窗口列
-- 依赖方: 港股数据更新失败排查（协作单 43.0 港股交易日判定 + 断点游标窗口绑定）
-- =====================================================================
-- 功能: 把断点续传游标 last_processed_code（V013 引入）与**日期窗口**绑定。
--       游标仅在窗口一致时可复用；窗口变化后旧游标作废，否则上一轮窗口的游标
--       会把本轮尚未覆盖新窗口的标的静默跳过，造成**永久数据缺口**（无任何报错）。
--       典型场景：9/25 窗口跑到 3886.HK 被中断，9/28 重跑时沿用该游标直接跳过
--       0~3886.HK，导致这些标的的 9/28 数据永久缺失。
-- 幂等性: ADD COLUMN IF NOT EXISTS，可重复执行。
-- 数据库: PostgreSQL 18.6
-- =====================================================================
ALTER TABLE etl_control
    ADD COLUMN IF NOT EXISTS last_processed_window VARCHAR(40);

COMMENT ON COLUMN etl_control.last_processed_window IS
    '断点续传游标绑定的日期窗口（格式 YYYY-MM-DD~YYYY-MM-DD，如 2026-09-25~2026-09-28）；'
    '与当前窗口不一致的游标将被忽略；整批跑完后与游标一并置 NULL';